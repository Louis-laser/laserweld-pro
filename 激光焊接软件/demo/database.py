def init_db():
    conn = sqlite3.connect(DB_PATH)
    c = conn.cursor()
    c.execute("""
        CREATE TABLE IF NOT EXISTS weld_params (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            material1 TEXT NOT NULL,
            material2 TEXT NOT NULL,
            thickness REAL NOT NULL,
            joint_type TEXT NOT NULL,
            speed REAL NOT NULL,
            power INTEGER NOT NULL,
            defocus TEXT DEFAULT '',
            shield_gas TEXT DEFAULT '',
            gas_flow REAL DEFAULT 0,
            fixture TEXT DEFAULT '',
            quality TEXT DEFAULT '',
            note TEXT DEFAULT '',
            is_premium INTEGER DEFAULT 0,
            image_url TEXT DEFAULT '',
            video_url TEXT DEFAULT '',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    
    # 检查是否有数据
    c.execute("SELECT COUNT(*) FROM weld_params")
    if c.fetchone()[0] == 0:
        for row in SEED_DATA:
            c.execute("""
                INSERT INTO weld_params 
                (material1, material2, thickness, joint_type, speed, power, defocus, shield_gas, gas_flow, fixture, quality, note)
                VALUES (?,?,?,?,?,?,?,?,?,?,?,?)
            """, row)
        conn.commit()
        print(f"✅ 已导入 {len(SEED_DATA)} 条默认参数")
    else:
        print(f"✅ 数据库已存在，跳过导入")
    
    conn.close()
    return DB_PATH

if __name__ == "__main__":
    init_db()
    print(f"📁 数据库路径: {DB_PATH}")
